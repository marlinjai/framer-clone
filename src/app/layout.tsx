import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import { unstable_rethrow } from "next/navigation";
import { getRequestLanguage, resolveSiteForRequest } from "@/server/sites/requestSite";
import { themeColorMode } from "@/lib/site/theme";
// The root layout imports NO stylesheet. In the App Router only the root layout
// owns `<html>`/`<body>`, so it wraps the published storefront under `(site)` too,
// and anything imported here ships to every visitor's page. Each surface links
// its own sheet instead: the editor's globals.css (plus the data-table CMS-grid
// sheets, MT-15) from `src/app/page.tsx`, `src/app/projects/layout.tsx` and
// `src/app/preview/layout.tsx`; the published site's `(site)/site.css` from
// `src/app/(site)/layout.tsx`. src/app/__tests__/publishedSheet.test.ts holds this.
// The Geist font classes stay here: the body carries them on every route.

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

// Neutral root metadata (MT-15): the old "Create Next App" / "Generated by
// create next app" defaults were editor scaffolding that leaked into the
// storefront `<head>`. The storefront supplies its own metadata via
// `src/app/(site)/layout.tsx` + per-page `generateMetadata`; editor surfaces
// can set their own titles. Nothing editor-specific ships to published sites:
// the platform icon is linked only on hosts that name no published site (the
// editor). A published site gets its own favicon from Site settings, and
// `/favicon.ico` answers per host (src/app/favicon.ico/route.ts).
export async function generateMetadata(): Promise<Metadata> {
  try {
    if (await resolveSiteForRequest()) return {};
  } catch (err) {
    unstable_rethrow(err);
    console.error("root layout: could not resolve the site for the icon links.", err);
    return {};
  }
  return { icons: { icon: "/platform-favicon.ico" } };
}

// `<html class>`: DEFAULT_HTML_CLASS, except on a published site whose theme forces
// `dark` (docs/plans/2026-11-02-theme-and-head.md, "Light and dark"), which wakes the
// base sheet's `.dark` variables and `&:is(.dark *)` rules for that site. A `system`
// site gets the default, because the server cannot know the visitor's setting. The
// editor and unknown hosts keep it, and a failure to resolve the site does too.
// test/score/refreshBase.ts reads the constant, so the score's page carries it.
const DEFAULT_HTML_CLASS = "light";

async function htmlClass(): Promise<string> {
  try {
    const site = await resolveSiteForRequest();
    return themeColorMode(site?.siteSettings.theme) === "dark" ? "dark" : DEFAULT_HTML_CLASS;
  } catch (err) {
    unstable_rethrow(err);
    console.error("root layout: could not resolve the site for its colour mode.", err);
    return DEFAULT_HTML_CLASS;
  }
}

// `<html lang>`: a published site's language from its Site settings
// (src/server/sites/requestSite.ts), `en` for the editor and unknown hosts.
// Only the root layout may render `<html>`, so it reads the request's site
// (one cached resolution shared with the (site) layout and the page).
export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  const [lang, className] = await Promise.all([getRequestLanguage(), htmlClass()]);
  return (
    <html lang={lang} className={className}>
      <body
        className={`${geistSans.variable} ${geistMono.variable} antialiased`}
      >
        {children}
      </body>
    </html>
  );
}
