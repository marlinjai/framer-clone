// pnpm generate:dom-members: the names a stored `id` or `name` must not take, read
// from real browsers. An `img` or `form` with such a name replaces a method of
// `document`, and a form control with one replaces a member of its form
// (src/lib/renderer/blockedNodes.ts). Checked in, because
// the renderers run without a browser to ask, and test/renderGate fails when the
// pinned browsers have a member this list lacks.

import fs from 'node:fs';
import { chromium, webkit } from 'playwright';

const OUT = 'src/lib/renderer/domMemberNames.generated.ts';

type Start = 'Document' | 'HTMLFormElement';

async function memberNames(starts: Start[]): Promise<string[]> {
  const names = new Set<string>();
  for (const type of [chromium, webkit]) {
    const browser = await type.launch();
    const page = await browser.newPage();
    const found = await page.evaluate((globals) => {
      const out: string[] = [];
      for (const start of globals) {
        const first = (window as unknown as Record<Start, { prototype: object }>)[start].prototype;
        for (let proto: object | null = first; proto; proto = Object.getPrototypeOf(proto)) {
          out.push(...Object.getOwnPropertyNames(proto));
        }
      }
      return out;
    }, starts);
    for (const name of found) names.add(name);
    await browser.close();
  }
  return [...names].sort();
}

const listing = (name: string, members: string[]): string[] => {
  const lines = members.reduce<string[]>((rows, member) => {
    const piece = `'${member}', `;
    const last = rows.at(-1);
    if (last !== undefined && last.length + piece.length <= 110) rows[rows.length - 1] = last + piece;
    else rows.push(`  ${piece}`);
    return rows;
  }, []);
  return [`export const ${name}: readonly string[] = [`, ...lines.map((line) => line.trimEnd()), '];'];
};

void (async () => {
  const all = await memberNames(['Document', 'HTMLFormElement']);
  const form = await memberNames(['HTMLFormElement']);
  fs.writeFileSync(
    OUT,
    [
      '// Generated by `pnpm generate:dom-members` from Document and HTMLFormElement and their',
      '// prototypes in Chromium and WebKit (scripts/generate-dom-members.ts). Do not edit by hand.',
      '',
      ...listing('DOM_MEMBER_NAMES', all),
      '',
      ...listing('FORM_MEMBER_NAMES', form),
      '',
    ].join('\n'),
  );
  console.log(`wrote ${OUT}`);
})();
