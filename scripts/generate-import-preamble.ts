// Writes the stylesheets the import's Tailwind compile may load, as constants. The worker
// has no file system, and a constant is also the guarantee: nothing else can be loaded.
// `importPreamble.test.ts` fails when an installed version moves past this file.
//
//   pnpm generate:import-preamble

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

// Both packages close their exports, so `require.resolve` cannot reach these files.
const packageDir = (name: string) => path.join(process.cwd(), 'node_modules', name);
const versionOf = (name: string): string => JSON.parse(readFileSync(path.join(packageDir(name), 'package.json'), 'utf8')).version;

export function importPreambleText(): string {
  const tailwind = readFileSync(path.join(packageDir('tailwindcss'), 'index.css'), 'utf8');
  const animate = readFileSync(path.join(packageDir('tw-animate-css'), 'dist/tw-animate.css'), 'utf8');
  return [
    '// Generated by scripts/generate-import-preamble.ts. Do not edit.',
    '',
    `export const TAILWIND_VERSION = ${JSON.stringify(versionOf('tailwindcss'))};`,
    `export const TW_ANIMATE_VERSION = ${JSON.stringify(versionOf('tw-animate-css'))};`,
    `export const TAILWIND_CSS = ${JSON.stringify(tailwind)};`,
    `export const TW_ANIMATE_CSS = ${JSON.stringify(animate)};`,
    '',
  ].join('\n');
}

export const IMPORT_PREAMBLE_FILE = path.join(process.cwd(), 'src/lib/reactImport/tailwind/preamble.generated.ts');

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  writeFileSync(IMPORT_PREAMBLE_FILE, importPreambleText());
}
