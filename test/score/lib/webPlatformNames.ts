// What the Custom section of the properties panel offers, read from the same
// pinned data as the score (universe.ts). The data packages are dev dependencies
// and far too large for the client bundle, so `pnpm generate:web-names` writes
// these names to src/lib/styles/webPlatformNames.generated.ts, and a test in
// src/lib/styles/__tests__ fails when the two drift apart.

import { cssProperties, htmlElementAttributes, htmlElements, htmlGlobalAttributes } from './universe';

/** The ARIA names worth suggesting: the data has one wildcard row, and any `aria-*` name is accepted. */
const ARIA_SUGGESTIONS = [
  'aria-controls', 'aria-current', 'aria-describedby', 'aria-expanded', 'aria-hidden',
  'aria-label', 'aria-labelledby', 'aria-live', 'role',
];

const sorted = (names: Iterable<string>) => [...new Set(names)].sort();

export interface WebPlatformNames {
  cssProperties: string[];
  legacyCssProperties: string[];
  elements: string[];
  globalAttributes: string[];
  elementAttributes: Record<string, string[]>;
}

export function buildWebPlatformNames(): WebPlatformNames {
  const css = cssProperties().filter((e) => e.id !== '--*');
  const elements = htmlElements().filter((e) => !e.excluded).map((e) => e.id);

  const byTag: Record<string, string[]> = {};
  for (const { id } of htmlElementAttributes().filter((e) => !e.excluded)) {
    const dot = id.indexOf('.');
    const name = id.slice(dot + 1);
    if (!name.startsWith('type_')) (byTag[id.slice(0, dot)] ??= []).push(name);
  }
  const elementAttributes = Object.fromEntries(Object.keys(byTag).sort().map((tag) => [tag, sorted(byTag[tag])]));

  return {
    cssProperties: sorted(css.filter((e) => !e.excluded).map((e) => e.id)),
    legacyCssProperties: sorted(css.filter((e) => e.excluded).map((e) => e.id)),
    elements: sorted(elements),
    globalAttributes: sorted([
      ...htmlGlobalAttributes()
        .filter((e) => !e.excluded && !['data_attributes', 'aria-*', 'style'].includes(e.id))
        .map((e) => e.id),
      ...ARIA_SUGGESTIONS,
    ]),
    elementAttributes,
  };
}

/** The generated module's source text. */
export function webPlatformNamesSource(): string {
  const names = buildWebPlatformNames();
  const lines = Object.entries(names).map(([key, value]) => `export const ${key} = ${JSON.stringify(value)};`);
  return [
    '// Generated by `pnpm generate:web-names` from mdn-data and @mdn/browser-compat-data',
    '// (test/score/lib/webPlatformNames.ts). Do not edit by hand.',
    '',
    ...lines,
    '',
  ].join('\n');
}
