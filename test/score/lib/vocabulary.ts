// What the AI generator accepts, derived from the score's own lists: the tags,
// attributes and properties the matrix includes. What is
// refused on top (blocked tags, handlers, reserved data attributes) is policy, not
// data, and lives in src/lib/ai/pageGen/schema.ts.

import fs from 'node:fs';
import path from 'node:path';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import {
  attributeSample,
  cssProperties,
  htmlElementAttributes,
  htmlElements,
  htmlGlobalAttributes,
  markupAttributeSample,
  mathmlAttributes,
  mathmlElements,
  namespaceOf,
  styleKeyOf,
  svgAttributes,
  svgElements,
} from './universe';

export interface WebVocabulary {
  tags: string[];
  svgTags: string[];
  mathmlTags: string[];
  styleKeys: string[];
  globalAttributes: string[];
  elementAttributes: Record<string, string[]>;
  propNames: Record<string, string>;
  reservedDataAttributes: string[];
}

/** Every data-* name in the source, tests and this generated list aside. */
export function dataAttributesInSource(): string[] {
  const names = new Set<string>();
  const walk = (dir: string) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const file = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        if (entry.name !== '__tests__') walk(file);
      } else if (/\.tsx?$/.test(entry.name) && !/\.test\.tsx?$/.test(entry.name) && entry.name !== 'webVocabulary.ts') {
        for (const m of fs.readFileSync(file, 'utf8').matchAll(/data-[a-z][a-z0-9-]*[a-z0-9]/g)) names.add(m[0]);
      }
    }
  };
  walk(path.resolve(process.cwd(), 'src'));
  return [...names].sort();
}

/** React's own spelling of each lower-case attribute it has one for, read from its development warning. */
function reactPropNames(names: string[]): Record<string, string> {
  const out: Record<string, string> = {};
  const original = console.error;
  console.error = (format: unknown, ...args: unknown[]) => {
    if (typeof format !== 'string' || !format.startsWith('Invalid DOM property')) return;
    out[String(args[0])] = String(args[1]);
  };
  for (const name of names) renderToStaticMarkup(React.createElement('div', { [name]: 'probe' }));
  console.error = original;
  // A production build of React has no such warning, and an empty map would pass silently.
  if (!out.colspan) throw new Error('React gave no attribute names: run this with a development build');
  return Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b)));
}

export function buildWebVocabulary(): WebVocabulary {
  const tags = htmlElements().filter((e) => !e.excluded).map((e) => e.id).sort();
  const styleKeys = cssProperties()
    .filter((e) => !e.excluded && e.id !== '--*')
    .map((e) => styleKeyOf(e.id))
    .sort();
  const global = new Set(htmlGlobalAttributes().filter((e) => !e.excluded).map((e) => attributeSample(e.id).prop.toLowerCase()));
  const perTag = new Map<string, Set<string>>();
  for (const entry of [...htmlElementAttributes(), ...svgAttributes(), ...mathmlAttributes()].filter((e) => !e.excluded)) {
    const { tag, prop } = markupAttributeSample(namespaceOf(entry.kind), entry.id);
    const [owner, name] = [entry.id.slice(0, entry.id.indexOf('.')), entry.id.slice(entry.id.indexOf('.') + 1)];
    // Both spellings: the markup's (stroke-width) and React's (strokeWidth).
    const names = name.startsWith('type_') ? [prop] : [prop, name];
    const into = owner === '*' ? global : perTag.get(tag) ?? new Set<string>();
    if (owner !== '*') perTag.set(tag, into);
    for (const spelling of names) into.add(spelling.toLowerCase());
  }
  // style has its own path, and aria-* and data-* are patterns, not names.
  const globalAttributes = [...global].filter((name) => name !== 'style' && !name.startsWith('aria-') && !name.startsWith('data-')).sort();
  const elementAttributes = Object.fromEntries(
    [...perTag.entries()].sort(([a], [b]) => (a < b ? -1 : 1)).map(([tag, names]) => [tag, [...names].sort()]),
  );
  const propNames = reactPropNames([...new Set([...globalAttributes, ...Object.values(elementAttributes).flat()])].sort());
  return {
    tags,
    svgTags: svgElements().filter((e) => !e.excluded).map((e) => e.id).sort(),
    mathmlTags: mathmlElements().filter((e) => !e.excluded).map((e) => e.id).sort(),
    styleKeys,
    globalAttributes,
    elementAttributes,
    propNames,
    reservedDataAttributes: dataAttributesInSource(),
  };
}

const list = (names: readonly string[]) => JSON.stringify(names).replace(/"/g, "'").replace(/,/g, ', ');

export function renderWebVocabulary(v: WebVocabulary): string {
  return [
    '// src/lib/ai/pageGen/webVocabulary.ts',
    '//',
    '// Generated by pnpm gen:web-vocabulary. Do not edit: the lists come from the data the',
    '// primitive score reads (mdn-data, @mdn/browser-compat-data, with its exclusions), which',
    '// are development dependencies. What is accepted of this is decided in ./schema.ts.',
    '',
    `export const WEB_TAGS: readonly string[] = ${list(v.tags)};`,
    '',
    '/** SVG and MathML elements, as the standards spell them: the case matters. */',
    `export const WEB_SVG_TAGS: readonly string[] = ${list(v.svgTags)};`,
    '',
    `export const WEB_MATHML_TAGS: readonly string[] = ${list(v.mathmlTags)};`,
    '',
    `export const WEB_STYLE_KEYS: readonly string[] = ${list(v.styleKeys)};`,
    '',
    '/** Attributes of every element, lower-cased. */',
    `export const WEB_GLOBAL_ATTRIBUTES: readonly string[] = ${list(v.globalAttributes)};`,
    '',
    '/** Attributes of one element, lower-cased: its HTML, SVG and MathML ones. */',
    'export const WEB_ELEMENT_ATTRIBUTES: Readonly<Record<string, readonly string[]>> = {',
    ...Object.entries(v.elementAttributes).map(([tag, names]) => `  ${JSON.stringify(tag).replace(/"/g, "'")}: ${list(names)},`),
    '};',
    '',
    "/** React's spelling of a lower-case attribute, where it differs. */",
    'export const WEB_ATTRIBUTE_PROP_NAMES: Readonly<Record<string, string>> = {',
    ...Object.entries(v.propNames).map(([name, prop]) => `  ${JSON.stringify(name).replace(/"/g, "'")}: '${prop}',`),
    '};',
    '',
    '/** The data attributes the source uses, scanned: never accepted from the model. */',
    `export const WEB_RESERVED_DATA_ATTRIBUTES: readonly string[] = ${list(v.reservedDataAttributes)};`,
    '',
  ].join('\n');
}
