// pnpm score:refresh-base: runs the production build and writes what a published page
// loads into test/score/data/published-base.{css,json}. Why those files exist:
// test/score/lib/publishedBase.ts.
//
// Read from the build, never composed: the sheets are the ones the build manifest lists
// for the published route, the font classes are the ones those sheets define. The
// build writes to .next, so do not run this beside a `next dev` in the same checkout.

import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { BASE_CSS_FILE, BASE_META_FILE, publishedBaseInputs, type PublishedBaseMeta } from './lib/publishedBase';

const ROOT = process.cwd();
const BUILD_DIR = path.join(ROOT, '.next');

/** The route's segments, outermost first: a page links the sheets of each. */
const PUBLISHED_ROUTE = ['/layout', '/(site)/layout', '/(site)/[...slug]/page'];

function build(): void {
  // The same stand-in as CI's verify job: the build needs the variable and never connects.
  const env = { ...process.env, DATABASE_URL: process.env.DATABASE_URL ?? 'postgresql://ci:ci@localhost:5432/framer_clone_ci' };
  const result = spawnSync('pnpm', ['build'], { stdio: 'inherit', env });
  if (result.status !== 0) throw new Error('pnpm build failed, so there is no sheet to read');
}

function routeSheets(): string[] {
  const manifest = JSON.parse(fs.readFileSync(path.join(BUILD_DIR, 'app-build-manifest.json'), 'utf8')) as { pages: Record<string, string[]> };
  const sheets = PUBLISHED_ROUTE.flatMap((segment) => {
    const files = manifest.pages[segment];
    if (!files) throw new Error(`the build manifest has no entry for ${segment}`);
    return files.filter((file) => file.endsWith('.css'));
  });
  if (sheets.length === 0) throw new Error('the build manifest lists no stylesheet for the published route');
  return [...new Set(sheets)];
}

/**
 * The font files as data URIs: under `page.setContent` a relative URL leads nowhere, and
 * `code` on a real page is set in the built Geist Mono.
 */
function inlineFonts(css: string): string {
  return css.replace(/url\((\/_next\/static\/media\/[^)]+\.woff2)\)/g, (_, url: string) => {
    const file = path.join(BUILD_DIR, url.replace('/_next/', ''));
    return `url(data:font/woff2;base64,${fs.readFileSync(file).toString('base64')})`;
  });
}

/** `geistSans.variable` and `geistMono.variable`: the build names these classes, so they are read from its sheet. */
function fontClasses(css: string): string[] {
  const of = (variable: string) => {
    const match = css.match(new RegExp(`\\.(__variable_\\w+)\\{${variable}:`));
    if (!match) throw new Error(`the built sheets define no class for ${variable}`);
    return match[1];
  };
  return [of('--font-geist-sans'), of('--font-geist-mono')];
}

/** The constant classes of the root layout, which cannot render outside a request. */
function layoutClasses(): { htmlClass: string; bodyClass: string } {
  const source = fs.readFileSync(path.join(ROOT, 'src/app/layout.tsx'), 'utf8');
  const html = source.match(/<html\b[^>]*\bclassName="([^"]*)"/);
  const body = source.match(/<body\s+className=\{`\$\{geistSans\.variable\} \$\{geistMono\.variable\} ([^`]*)`\}/);
  if (!html || !body) throw new Error('src/app/layout.tsx no longer has the html and body classes this script reads');
  return { htmlClass: html[1], bodyClass: body[1] };
}

function main(): void {
  build();
  const sheets = routeSheets();
  const css = sheets.map((sheet) => fs.readFileSync(path.join(BUILD_DIR, sheet), 'utf8')).join('\n');
  const { htmlClass, bodyClass } = layoutClasses();
  const meta: PublishedBaseMeta = {
    _doc: 'Generated by pnpm score:refresh-base from the production build. Do not edit. Why it exists: test/score/lib/publishedBase.ts.',
    htmlClass,
    bodyClass: [...fontClasses(css), bodyClass].join(' '),
    sheets,
    inputs: publishedBaseInputs(),
  };
  fs.writeFileSync(BASE_CSS_FILE, `${inlineFonts(css)}\n`);
  fs.writeFileSync(BASE_META_FILE, `${JSON.stringify(meta, null, 2)}\n`);
  console.log(`Wrote ${path.relative(ROOT, BASE_CSS_FILE)} from ${sheets.join(', ')}`);
}

main();
